/// Typed access to the report exports (CLAUDE.md §8, §9; ADR 0017 §10).
class ReportsApi {
  ReportsApi(this._dio);

  final Dio _dio;

  static String _seg(String value) => ChangesApi.seg(value);

  /// `POST /reports`: 201 with a finished report (`done`) or 202 with a
  /// `pending` one generated by the worker — then poll [get].
  Future<Report> create(ReportRequest request) async {
    final response = await _dio.post<Map<String, dynamic>>(
      '/reports',
      data: request.toJson(),
    );
    return Report.fromJson(response.data ?? const {});
  }

  /// `GET /reports`, newest first. [companyId] null = every report the user
  /// may see (the auditor's own multi-company reports included).
  Future<PageResult<Report>> list({
    String? companyId,
    String? kind,
    String? status,
    int limit = 20,
    int offset = 0,
  }) async {
    final response = await _dio.get<Map<String, dynamic>>(
      '/reports',
      queryParameters: {
        'company_id': ?companyId,
        'kind': ?kind,
        'status': ?status,
        'limit': limit,
        'offset': offset,
      },
    );
    return PageResult.fromJson(response.data ?? const {}, Report.fromJson);
  }

  /// `GET /reports/{id}` — status of a report.
  Future<Report> get(String reportId) async {
    final response = await _dio.get<Map<String, dynamic>>(
      '/reports/${_seg(reportId)}',
    );
    return Report.fromJson(response.data ?? const {});
  }

  /// `GET /reports/{id}/download` — the file (audited by the API).
  Future<DownloadedFile> download(Report report) => fetchFile(
    _dio,
    '/reports/${_seg(report.id)}/download',
    fallbackName: report.fallbackFilename,
  );

  /// `GET /companies/{cid}/changes/export.csv` with the register filters
  /// (period, statuses, …; the CSV has no sort or paging).
  Future<DownloadedFile> exportCsv(String companyId, RegisterFilters filters) {
    final query = filters.toApiQuery()
      ..remove('sort')
      ..remove('limit')
      ..remove('offset');
    return fetchFile(
      _dio,
      '/companies/${_seg(companyId)}/changes/export.csv',
      query: query,
      fallbackName: 'rejestr-zmian.csv',
    );
  }
}

final reportsApiProvider = Provider<ReportsApi>(
  (ref) => ReportsApi(ref.watch(apiClientProvider)),
);

/// How often and how long a `pending` report is polled (tests shorten it).
class ReportPolling {
  const ReportPolling({
    this.interval = const Duration(seconds: 2),
    this.timeout = const Duration(minutes: 15),
  });

  final Duration interval;

  /// The worker's `job_timeout` is 900 s (ADR 0017 §8); after that the
  /// report will not finish on its own.
  final Duration timeout;

  int get maxAttempts =>
      (timeout.inMilliseconds / interval.inMilliseconds).ceil();
}

final reportPollingProvider = Provider<ReportPolling>(
  (ref) => const ReportPolling(),
);

/// Key of the report list: company (null = all visible), kind, page offset.
typedef ReportListKey = ({String? companyId, String? kind, int offset});

const int reportPageSize = 20;

final reportListProvider = FutureProvider.autoDispose
    .family<PageResult<Report>, ReportListKey>(
      (ref, key) => ref
          .watch(reportsApiProvider)
          .list(
            companyId: key.companyId,
            kind: key.kind,
            limit: reportPageSize,
            offset: key.offset,
          ),
    );
