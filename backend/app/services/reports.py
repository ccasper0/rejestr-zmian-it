async def _count(
    session: AsyncSession, companies: Sequence[Company], filters: changes_service.ChangeFilters
) -> int:
    total = 0
    for company in companies:
        total += await changes_service.count_changes(session, company.id, filters)
    return total


def _check_period(filters: changes_service.ChangeFilters, *, required: bool) -> None:
    if required and (filters.period_from is None or filters.period_to is None):
        raise _unprocessable(
            "report.period_required",
            "Podaj okres raportu (początek i koniec).",
            fields=["period_from", "period_to"],
        )
    if (
        filters.period_from is not None
        and filters.period_to is not None
        and filters.period_from >= filters.period_to
    ):
        raise _unprocessable(
            "report.invalid_period",
            "Początek okresu musi być wcześniejszy niż jego koniec.",
            fields=["period_from", "period_to"],
        )


def _too_large(count: int, maximum: int) -> ProblemError:
    return _unprocessable(
        "report.too_large",
        f"Raport obejmowałby {count} zmian (maksymalnie {maximum}). Zawęź okres lub filtry.",
        change_count=count,
        max_changes=maximum,
    )


async def _new_row(
    session: AsyncSession,
    *,
    request: ReportRequest,
    exporter: Exporter,
    report_format: ReportFormat,
    count: int,
) -> ReportExport:
    now = await changes_service.db_now(session)
    report = ReportExport(
        company_id=request.company.id if request.company else None,
        number=await next_report_number(session, request.company, at=now),
        kind=request.kind.value,
        format=report_format.value,
        change_id=request.change_id,
        scope_company_ids=sorted(c.id for c in request.companies),
        period_from=request.filters.period_from,
        period_to=request.filters.period_to,
        filters=filters_json(request.filters) if request.kind == ReportKind.REGISTER else {},
        include_audit_trail=request.include_audit_trail,
        generated_by_id=exporter.user_id,
        status=ReportStatus.PENDING.value,
        change_count=count,
    )
    session.add(report)
    await session.flush()
    await session.refresh(report)
    return report


async def create_report(
    session: AsyncSession,
    *,
    request: ReportRequest,
    exporter: Exporter,
    options: ReportOptions,
    renderer: PdfRenderer,
    enqueue: Enqueue,
    job_extra: Mapping[str, Any] | None = None,
    failure_db: Database | None = None,
) -> ReportExport:
    """``POST /reports``: a PDF register report or change card.

    Synchronous (the row is ``done`` when this returns), unless a register report has more
    changes than ``options.async_threshold``: then the row stays ``pending`` and the job
    is enqueued for the worker (before COMMIT - the job retries until it sees the row)."""
    if request.kind == ReportKind.CHANGE_CARD:
        if request.company is None:
            raise _unprocessable(
                "report.invalid_kind",
                "Kartę zmiany można wygenerować tylko dla jednej spółki.",
                fields=["company_id"],
            )
        if request.change_id is None:
            raise _unprocessable(
                "report.change_required", "Wskaż zmianę (change_id).", fields=["change_id"]
            )
        exists = (
            await session.execute(
                select(Change.id).where(
                    Change.company_id == request.company.id, Change.id == request.change_id
                )
            )
        ).scalar_one_or_none()
        if exists is None:
            raise changes_service.not_found()
        count = 1
    else:
        if request.change_id is not None:
            raise _unprocessable(
                "report.invalid_kind",
                "Raport rejestru nie dotyczy pojedynczej zmiany (pomiń change_id).",
                fields=["change_id"],
            )
        _check_period(request.filters, required=True)
        count = await _count(session, request.companies, request.filters)
        if count > options.max_changes:
            raise _too_large(count, options.max_changes)

    report = await _new_row(
        session, request=request, exporter=exporter, report_format=ReportFormat.PDF, count=count
    )
    extra = {"admin_path": True} if request.admin_path else None
    if request.kind == ReportKind.REGISTER and count > options.async_threshold:
        await record_event(
            session, report=report, exporter=exporter, event=ExportEvent.REQUESTED, extra=extra
        )
        await enqueue(
            {
                "report_id": str(report.id),
                "user_id": str(exporter.user_id),
                "company_ids": [str(c) for c in report.scope_company_ids],
                "admin_path": request.admin_path,
                **(job_extra or {}),
            }
        )
        return report
    report, _ = await _generate_now(
        session,
        report,
        exporter=exporter,
        renderer=renderer,
        options=options,
        extra=extra,
        failure_db=failure_db,
    )
    return report


async def export_csv(
    session: AsyncSession,
    *,
    company: Company,
    filters: changes_service.ChangeFilters,
    exporter: Exporter,
    options: ReportOptions,
    admin_path: bool = False,
    failure_db: Database | None = None,
) -> tuple[ReportExport, bytes]:
    """``GET /companies/{cid}/changes/export.csv`` - always synchronous, numbered,
    stored and audited like every export."""
    _check_period(filters, required=False)
    count = await changes_service.count_changes(session, company.id, filters)
    if count > options.max_changes:
        raise _too_large(count, options.max_changes)
    request = ReportRequest(
        kind=ReportKind.REGISTER,
        company=company,
        companies=[company],
        filters=filters,
        admin_path=admin_path,
    )
    report = await _new_row(
        session, request=request, exporter=exporter, report_format=ReportFormat.CSV, count=count
    )
    return await _generate_now(
        session,
        report,
        exporter=exporter,
        renderer=_no_pdf,
        options=options,
        extra={"admin_path": True} if admin_path else None,
        failure_db=failure_db,
    )


def _no_pdf(_: str) -> bytes:  # pragma: no cover - CSV never renders a PDF
    raise RuntimeError("a CSV export does not render a PDF")


