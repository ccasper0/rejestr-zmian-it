@dataclass(frozen=True, slots=True)
class Exporter:
    """Who exports: the audit actor of every company chain the export is recorded in."""

    user_id: UUID
    display_name: str
    # Membership role values per company; ``app_admin`` is a global role (not in here).
    roles_by_company: Mapping[UUID, frozenset[str]]
    is_app_admin: bool = False

    def actor(self, company_id: UUID | None) -> Actor:
        roles = set(self.roles_by_company.get(company_id, frozenset())) if company_id else set()
        if self.is_app_admin:
            roles.add("app_admin")
        return Actor(id=self.user_id, display=self.display_name, roles=tuple(roles))


