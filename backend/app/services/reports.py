@dataclass(frozen=True, slots=True)
class ReportVisibility:
    """Which rows a user may list (``GET /reports``), decided by ``app.permissions``."""

    all_rows: bool = False  # the app admin
    register_company_ids: frozenset[UUID] = frozenset()  # export.register
    card_company_ids: frozenset[UUID] = frozenset()  # export.change_card only
    user_id: UUID | None = None  # own multi-company reports


@dataclass(frozen=True, slots=True)
class ReportPage:
    rows: list[ReportExport]
    total: int
    companies: Mapping[UUID, Company]
    users: Mapping[UUID, User]
    change_numbers: Mapping[UUID, str]


async def list_reports(
    session: AsyncSession,
    visibility: ReportVisibility,
    *,
    company_id: UUID | None = None,
    kind: ReportKind | None = None,
    status: ReportStatus | None = None,
    limit: int,
    offset: int,
) -> ReportPage:
    """Newest first."""
    allowed: list[ColumnElement[bool]] = []
    if visibility.all_rows:
        allowed.append(ReportExport.id.is_not(None))
    if visibility.register_company_ids:
        allowed.append(ReportExport.company_id.in_(list(visibility.register_company_ids)))
    if visibility.card_company_ids:
        allowed.append(
            and_(
                ReportExport.company_id.in_(list(visibility.card_company_ids)),
                ReportExport.kind == ReportKind.CHANGE_CARD.value,
            )
        )
    if visibility.user_id is not None:
        allowed.append(
            and_(
                ReportExport.company_id.is_(None),
                ReportExport.generated_by_id == visibility.user_id,
            )
        )
    if not allowed:
        return ReportPage([], 0, {}, {}, {})
    conditions: list[ColumnElement[bool]] = [or_(*allowed)]
    if company_id is not None:
        conditions.append(ReportExport.company_id == company_id)
    if kind is not None:
        conditions.append(ReportExport.kind == kind.value)
    if status is not None:
        conditions.append(ReportExport.status == status.value)
    total = (
        await session.execute(select(func.count()).select_from(ReportExport).where(*conditions))
    ).scalar_one()
    rows = list(
        (
            await session.execute(
                select(ReportExport)
                .where(*conditions)
                .order_by(ReportExport.created_at.desc(), ReportExport.number.desc())
                .limit(limit)
                .offset(offset)
            )
        ).scalars()
    )
    return ReportPage(rows, int(total), *await describe(session, rows))


async def describe(
    session: AsyncSession, rows: Sequence[ReportExport]
) -> tuple[dict[UUID, Company], dict[UUID, User], dict[UUID, str]]:
    """Companies, authors and change numbers of the rows (for the API output)."""
    company_ids = {c for r in rows for c in r.scope_company_ids}
    companies = (
        {
            c.id: c
            for c in (
                await session.execute(select(Company).where(Company.id.in_(list(company_ids))))
            ).scalars()
        }
        if company_ids
        else {}
    )
    users = await changes_service.users_by_id(session, [r.generated_by_id for r in rows])
    change_ids = [r.change_id for r in rows if r.change_id is not None]
    numbers = (
        dict(
            (
                await session.execute(
                    select(Change.id, Change.number).where(Change.id.in_(change_ids))
                )
            ).all()
        )
        if change_ids
        else {}
    )
    return companies, users, numbers


