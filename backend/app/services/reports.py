async def build_change_card_data(
    session: AsyncSession,
    *,
    report: ReportExport,
    company: Company,
    generated_by: str,
    now: datetime,
) -> dict[str, Any]:
    """The data of a change card (§9 "Karta zmiany")."""
    assert report.change_id is not None  # noqa: S101 - CHECK ck_report_exports_kind_shape
    view = await changes_service.get_change_view(
        session,
        company=company,
        change_id=report.change_id,
        actor=changes_service.ChangeActor(
            audit=Actor.system(), user_id=report.generated_by_id, roles=frozenset()
        ),
        now=now,
    )
    change = view.change
    names = _Names(
        users={uid: u.display_name for uid, u in view.users.items()},
        categories={cid: _category_label(c) for cid, c in view.categories.items()},
        cis={i.ci_id: i.current_identifier for i in view.items},
    )
    # The card carries the WHOLE trail (no limit, ADR 0017 §14).
    trail = (await _trail_rows(session, company.id, [change.id], limit=None)).entries.get(
        change.id, []
    )
    users_ids, category_ids, ci_ids = _diff_ids(r.diff or {} for r in trail)
    attachments = list(
        (
            await session.execute(
                select(Attachment)
                .where(Attachment.company_id == company.id, Attachment.change_id == change.id)
                .order_by(Attachment.created_at, Attachment.id)
            )
        ).scalars()
    )
    await _load_names(
        session,
        company_ids=[company.id],
        users=[*users_ids, *(a.uploaded_by_id for a in attachments)],
        categories=category_ids,
        cis=ci_ids,
        names=names,
    )
    ci_types = {r.code: r.name for r in await session.execute(select(CiType.code, CiType.name))}
    timeline: list[dict[str, Any]] = []
    for entry in trail:
        context: Mapping[str, Any] = entry.context or {}
        if entry.entity_type != EntityType.CHANGE.value:
            continue
        if entry.action == AuditAction.CREATE.value:
            status = str(context.get("status") or ChangeStatus.DRAFT.value)
        elif entry.action == AuditAction.TRANSITION.value and context.get(
            "from_status"
        ) != context.get("to_status"):
            status = str(context.get("to_status"))
        else:
            continue
        timeline.append(
            {
                "status": status,
                "at": entry.occurred_at,
                "simulated_at": context.get("simulated_at"),
                "actor": entry.actor_display,
            }
        )
    return {
        "format": REPORT_DATA_FORMAT,
        "kind": ReportKind.CHANGE_CARD.value,
        "number": report.number,
        "generated_at": now,
        "generated_by": {"id": report.generated_by_id, "name": generated_by},
        "company": _company_data(company),
        "change": {
            "id": change.id,
            "number": change.number,
            "title": change.title,
            "status": change.status,
            "change_type": change.change_type,
            "risk": change.risk,
            "category": names.category(change.category_id),
            "subcategory": names.category(change.subcategory_id),
            "description": change.description,
            "implementation_plan": change.implementation_plan,
            "rollback_plan": change.rollback_plan,
            "impact": change.impact,
            "requirement_ref": change.requirement_ref,
            "ticket_ref": change.ticket_ref,
            **_people(names, change),
            "window_start": change.window_start,
            "window_end": change.window_end,
            "created_at": change.created_at,
            "approved_at": change.approved_at,
            "implemented_at": change.implemented_at,
            "verified_at": change.verified_at,
            "rejected_at": change.rejected_at,
            "supersedes_number": view.links.supersedes_number,
            "superseded_by": [
                {"number": c.number, "status": c.status} for c in view.links.superseded_by
            ],
            "version": change.version,
        },
        "ci": [
            {
                "identifier": item.identifier,
                "name": item.name,
                "type": ci_types.get(item.ci_type_code, item.ci_type_code),
                "snapshot": item.snapshot,
                "owner": names.user(item.owner_user_id),
            }
            for item in view.items
        ],
        "consents": [
            {
                "ci": names.ci(c.ci_id),
                "owner": names.user(c.owner_user_id),
                "at": c.consented_at,
                "valid": c.valid,
            }
            for c in view.consents
        ],
        "deviations": [
            {"kind": d.kind.value, "critical": d.critical, "message": d.message_pl}
            for d in view.deviations
        ],
        "timeline": timeline,
        "comments": [
            {
                "author": names.user(c.author_id),
                "created_at": c.created_at,
                "body": c.body,
                "action": c.action,
            }
            for c in view.comments
        ],
        "attachments": [
            {
                "filename": a.filename,
                "content_type": a.content_type,
                "size": a.size,
                "sha256": a.sha256,
                "uploaded_by": names.user(a.uploaded_by_id),
                "created_at": a.created_at,
            }
            for a in attachments
        ],
        "audit_trail": [_entry_data(e, names) for e in trail],
        "chain_verification": await _verification(session, company, now),
    }


# --------------------------------------------------------------------------- storage


def _storage_key(report: ReportExport) -> str:
    owner = str(report.company_id) if report.company_id else "all"
    return f"reports/{owner}/{report.id}.{report.format}"


def resolve(storage_root: Path, key: str) -> Path:
    root = storage_root.resolve()
    path = (root / key).resolve()
    if not path.is_relative_to(root):  # pragma: no cover - keys are generated, never input
        raise ValueError("storage key outside the storage root")
    return path


def _write(path: Path, content: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    partial = path.with_name(path.name + ".part")
    with partial.open("xb") as handle:
        handle.write(content)
        handle.flush()
        os.fsync(handle.fileno())
    os.replace(partial, path)


def _remove(path: Path) -> None:
    path.unlink(missing_ok=True)


# --------------------------------------------------------------------------- audit


def _context(
    report: ReportExport,
    event: ExportEvent,
    *,
    company_numbers: Mapping[UUID, str] | None = None,
    verification: Mapping[str, Any] | None = None,
    extra: Mapping[str, object] | None = None,
) -> dict[str, object]:
    context: dict[str, object] = {
        "event": event.value,
        "number": report.number,
        "kind": report.kind,
        "format": report.format,
        "status": report.status,
        "data_sha256": report.data_sha256,
        "file_sha256": report.file_sha256,
        "size": report.size,
        "change_count": report.change_count,
        "period_from": report.period_from,
        "period_to": report.period_to,
        "filters": report.filters,
        "include_audit_trail": report.include_audit_trail,
    }
    if report.company_id is None:
        context["scope_company_ids"] = sorted(str(c) for c in report.scope_company_ids)
    if report.change_id is not None:
        context["change_id"] = report.change_id
        if company_numbers:
            context["change_number"] = company_numbers.get(report.change_id)
    if verification is not None:
        context["chain"] = {
            key: verification[key]
            for key in ("ok", "checked", "first_broken_seq", "head_seq", "head_hash")
        }
    result = {k: v for k, v in context.items() if v is not None}
    # Explicit extras are kept as given (e.g. ``found_sha256: None`` of a missing file).
    result.update(extra or {})
    return result


async def _record(
    session: AsyncSession,
    *,
    company_id: UUID,
    actor: Actor,
    report: ReportExport,
    context: Mapping[str, object],
) -> None:
    """One ``report`` / ``export`` entry in the company chain - ALWAYS under a savepoint:
    a chain found broken refuses the append (ADR 0009 §4), whatever any earlier
    verification said, and then the entry goes to the GLOBAL chain with
    ``target_company_id`` and ``chain_append_failed`` - an export is never left unrecorded
    (if that fails too, the export fails)."""

    async def append(chain: UUID | None, extra: Mapping[str, object]) -> None:
        await audit.record(
            session,
            company_id=chain,
            actor=actor,
            entity_type=EntityType.REPORT,
            entity_id=report.id,
            action=AuditAction.EXPORT,
            context={**context, **extra},
        )

    try:
        async with session.begin_nested():
            await append(company_id, {})
        return
    except DBAPIError:
        logger.error("audit chain %s refused the export entry", company_id)
    await append(None, {"target_company_id": company_id, "chain_append_failed": True})


async def record_event(
    session: AsyncSession,
    *,
    report: ReportExport,
    exporter: Exporter,
    event: ExportEvent,
    verifications: Mapping[UUID, Mapping[str, Any]] | None = None,
    extra: Mapping[str, object] | None = None,
) -> None:
    """The export entry in the chain of EVERY company of the report (a multi-company
    report is recorded in each of them, ADR 0017 §6); company chains in id order (one lock
    order for every writer, ADR 0006 §7)."""
    numbers: dict[UUID, str] = {}
    if report.change_id is not None:
        number = (
            await session.execute(select(Change.number).where(Change.id == report.change_id))
        ).scalar_one_or_none()
        if number is not None:
            numbers[report.change_id] = number
    for company_id in sorted(report.scope_company_ids):
        await _record(
            session,
            company_id=company_id,
            actor=exporter.actor(company_id),
            report=report,
            context=_context(
                report,
                event,
                company_numbers=numbers,
                verification=(verifications or {}).get(company_id),
                extra=extra,
            ),
        )


