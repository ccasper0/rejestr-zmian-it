"""Report exports: register report and change card (PDF), register CSV (CLAUDE.md §9;
ADR 0017).

Pipeline (one for every kind and format):

1. collect the data (register filters of ``GET /companies/{cid}/changes``, deviations from
   :mod:`app.domain.deviations`, the audit trails and the verification of the audit chain
   at the moment of generation) into ONE plain structure;
2. ``data_sha256`` = sha256 of its canonical JSON (:mod:`app.domain.canonical` - the very
   serialization of the audit chain);
3. render ONLY that structure (Jinja2 -> HTML -> WeasyPrint PDF, or CSV) - the footer of
   every page carries the report number and ``data_sha256``;
4. store the file (``STORAGE_PATH/reports/...``), complete the ``report_exports`` row and
   append the ``report`` / ``export`` audit entry (number, ``data_sha256``) to the chain of
   every company of the report - all in the caller's transaction.

Register reports with more changes than ``REPORT_ASYNC_THRESHOLD`` are generated by the
worker (``app.worker.generate_report``): the request creates the ``pending`` row (audited,
``event = requested``) and enqueues the job; the worker completes it later.

Every query filters by company explicitly; RLS is the second line of defence.
"""

