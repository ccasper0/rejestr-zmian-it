async def next_report_number(
    session: AsyncSession, company: Company | None, *, at: datetime
) -> str:
    """``RAP-{PREFIX}-{YYYY}-{NNNN}`` / ``RAP-{YYYY}-{NNNN}`` (multi-company), counter per
    (company, year in Europe/Warsaw) locked until the end of the transaction."""
    year = await numbering_year(session, at)
    company_id = company.id if company is not None else None
    await session.execute(
        pg_insert(ReportNumberSequence)
        .values(company_id=company_id, year=year, last_value=0)
        .on_conflict_do_nothing(constraint="uq_report_number_sequences_company_id_year")
    )
    owner: ColumnElement[bool] = (
        ReportNumberSequence.company_id.is_(None)
        if company_id is None
        else ReportNumberSequence.company_id == company_id
    )
    row = (
        await session.execute(
            select(ReportNumberSequence.id, ReportNumberSequence.last_value)
            .where(owner, ReportNumberSequence.year == year)
            .with_for_update()
        )
    ).one()
    value = int(row.last_value) + 1
    await session.execute(
        update(ReportNumberSequence)
        .where(ReportNumberSequence.id == row.id)
        .values(last_value=value)
        .execution_options(synchronize_session=False)
    )
    return format_report_number(company.prefix if company else None, year, value)


# --------------------------------------------------------------------------- filters


def filters_json(filters: changes_service.ChangeFilters) -> dict[str, Any]:
    """The register filters as stored in ``report_exports.filters`` (period separately)."""
    approved_by: str | None = None
    if filters.approved_by_system:
        approved_by = "system"
    elif filters.approved_by_id is not None:
        approved_by = str(filters.approved_by_id)
    result: dict[str, Any] = {
        "period_by": filters.period_by,
        "status": [s.value for s in filters.statuses],
        "type": [t.value for t in filters.types],
        "category": [str(c) for c in filters.categories],
        "ci": [str(c) for c in filters.cis],
        "assignee": str(filters.assignee_id) if filters.assignee_id else None,
        "approver": str(filters.approver_id) if filters.approver_id else None,
        "approved_by": approved_by,
        "q": filters.q.strip() if filters.q and filters.q.strip() else None,
    }
    return result


def filters_from_json(
    stored: Mapping[str, Any], period_from: datetime | None, period_to: datetime | None
) -> changes_service.ChangeFilters:
    approved_by = stored.get("approved_by")
    return changes_service.ChangeFilters(
        period_from=period_from,
        period_to=period_to,
        period_by="implemented" if stored.get("period_by") == "implemented" else "created",
        statuses=tuple(ChangeStatus(s) for s in stored.get("status") or ()),
        types=tuple(ChangeType(t) for t in stored.get("type") or ()),
        categories=tuple(UUID(c) for c in stored.get("category") or ()),
        cis=tuple(UUID(c) for c in stored.get("ci") or ()),
        assignee_id=UUID(stored["assignee"]) if stored.get("assignee") else None,
        approver_id=UUID(stored["approver"]) if stored.get("approver") else None,
        approved_by_id=UUID(approved_by) if approved_by and approved_by != "system" else None,
        approved_by_system=approved_by == "system",
        q=stored.get("q"),
    )


