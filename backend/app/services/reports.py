def _not_ready(report: ReportExport) -> ProblemError:
    if report.status == ReportStatus.FAILED.value:
        return ProblemError(
            status=409,
            code="report.failed",
            detail="Generowanie raportu nie powiodło się - wygeneruj raport ponownie.",
            extra={"status": report.status},
        )
    return ProblemError(
        status=409,
        code="report.not_ready",
        detail="Raport jest jeszcze generowany. Spróbuj ponownie za chwilę.",
        extra={"status": report.status},
    )


async def _record_integrity_failure(
    db: Database,
    report: ReportExport,
    *,
    exporter: Exporter,
    code: str,
    found_sha256: str | None,
    extra: Mapping[str, object] | None,
) -> None:
    """``integrity_failed`` entry of a refused download, in a SEPARATE transaction (the
    request fails with 500 and rolls back - the evidence must survive, like
    ``record_access_denied``): the chain of every company of the report, the global chain
    with ``target_company_id`` when a company chain refuses the append. Never raises."""
    company_ids = list(report.scope_company_ids)
    context = _context(
        report,
        ExportEvent.INTEGRITY_FAILED,
        extra={
            **(extra or {}),
            "code": code,
            "expected_sha256": report.file_sha256,
            "found_sha256": found_sha256,
        },
    )

    async def write(session: AsyncSession) -> None:
        for company_id in sorted(company_ids):
            await _record(
                session,
                company_id=company_id,
                actor=exporter.actor(company_id),
                report=report,
                context=context,
            )

    try:
        await run_in_separate_transaction(
            db, write, company_ids=company_ids, user_id=exporter.user_id
        )
    except Exception:
        logger.exception("the integrity failure of report %s could not be recorded", report.id)


async def download(
    session: AsyncSession,
    report: ReportExport,
    *,
    exporter: Exporter,
    storage_root: Path,
    db: Database | None = None,
    extra: Mapping[str, object] | None = None,
) -> bytes:
    """The content of the stored file of a finished report.

    The file is read ONCE and those very bytes are checked against the recorded sha256
    and returned (no second read that could see another file - TOCTOU). The download is
    audited in every company chain of the report BEFORE the file is sent (committed with
    the request). A missing or modified file is never served; the refusal is recorded
    (``integrity_failed``, separate transaction - ``db``) and the request fails with 500."""
    if report.status != ReportStatus.DONE.value or report.storage_key is None:
        raise _not_ready(report)
    path = resolve(storage_root, report.storage_key)
    try:
        content = await asyncio.to_thread(path.read_bytes)
    except (FileNotFoundError, IsADirectoryError, NotADirectoryError):
        logger.error("report %s: stored file is missing", report.number)
        if db is not None:
            await _record_integrity_failure(
                db,
                report,
                exporter=exporter,
                code="report.file_missing",
                found_sha256=None,
                extra=extra,
            )
        raise ProblemError(
            status=500,
            code="report.file_missing",
            detail="Plik raportu jest niedostępny w magazynie. Wygeneruj raport ponownie.",
        ) from None
    digest = hashlib.sha256(content).hexdigest()
    if digest != report.file_sha256:
        logger.error("report %s: stored file does not match its sha256", report.number)
        if db is not None:
            await _record_integrity_failure(
                db,
                report,
                exporter=exporter,
                code="report.file_corrupted",
                found_sha256=digest,
                extra=extra,
            )
        raise ProblemError(
            status=500,
            code="report.file_corrupted",
            detail="Plik raportu został zmieniony w magazynie i nie zostanie wydany. "
            "Skontaktuj się z administratorem.",
        )
    await record_event(
        session, report=report, exporter=exporter, event=ExportEvent.DOWNLOADED, extra=extra
    )
    return content


